def bold(s):return re.sub(r'\*\*(.+?)\*\*',r'<strong>\1</strong>',s)
def add(title,img,points,note,kind='content',sources=None):
    image=''
    if img:
        path=('./assets/figures/'+img[4:]+'.svg') if img.startswith('uml:') else ('./assets/story/'+img+'.svg')
        image=f'<figure class="story-figure"><img src="{path}" alt="{escape(title)}的机制图" /></figure>\n\n'
    out=[]
    for p in points:
        s=bold(p)
        if s.startswith(('> ','<','|')):
            if out and out[-1]!='':out.append('')
            out.append(s)
        elif s.startswith('  - '):
            out.append(s)
        else:
            if out and out[-1].startswith(('> ','|')):out.append('')
            out.append('- '+s)
    body=image+'\n'.join(out)
    pages.append(dict(title=title,body=body,note=note,kind=kind,sources=sources or [STATE,CP,DATA]))
